        <section class="contenedor">
            <h2 class="titulo-seccion al-izq">¿El nuevo baremo perjudica al trabajador?</h2>
            <p><strong>Sí, a la gran mayoría de los trabajadores los perjudica.</strong> El Decreto 549/2025 reduce los porcentajes de incapacidad en muchas de las lesiones laborales más comunes, lo que perjudica directamente a las indemnizaciones de los trabajadores.</p>
            <p>Los principales cambios son:</p>
            <ul style="margin-top: 1rem; padding-left: 1.5rem; list-style: disc;">
                <li><strong>Porcentajes fijos:</strong> desaparecen los rangos del Decreto 659/96 y cada lesión tiene un porcentaje único, lo que reduce el margen para obtener una valoración más alta en sede administrativa.</li>
                <li><strong>Menores porcentajes:</strong> lesiones habituales, como las hernias de disco o algunas lesiones de rodilla, reciben porcentajes inferiores a los previstos en el baremo anterior.</li>
                <li><strong>Daño psicológico más restringido:</strong> solo se reconoce en casos de "extrema gravedad", limitando su aplicación en la mayoría de los accidentes laborales.</li>
                <li><strong>Examen físico no siempre obligatorio:</strong> en determinados casos, la incapacidad podrá evaluarse únicamente con la documentación médica disponible.</li>
                <li><strong>Cambios en los factores de ponderación:</strong> se modifican los adicionales por edad y tipo de actividad, reduciendo su impacto en el cálculo final de la incapacidad.</li>
            </ul>
        </section>
