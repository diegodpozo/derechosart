            <h2 class="titulo-seccion al-izq">¿Qué es el Baremo de Incapacidades Laborales?</h2>
            <p>El <strong>Baremo</strong> es la tabla que utilizan los médicos de las Comisiones Médicas de la Superintendencia de Riesgos del Trabajo (SRT) y los peritos judiciales para determinar el <strong>porcentaje de incapacidad</strong> que dejó un accidente laboral o una enfermedad profesional.</p>
            <p>En otras palabras, es la herramienta que permite establecer, desde el punto de vista médico-legal, cuánto afectó esa lesión tu capacidad para trabajar. Ese porcentaje será uno de los elementos fundamentales para <strong>calcular la indemnización</strong> que debe abonarte la ART.</p>
            <p>El <strong>Decreto 549/2025</strong>, publicado en el Boletín Oficial el 6 de agosto de 2025, entró en vigencia el <strong>1° de febrero de 2026</strong> y se aplica a todos los expedientes en los que la incapacidad todavía no haya sido dictaminada, tanto en sede administrativa como judicial.</p>
